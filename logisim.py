class tool:
   def __init__(self,name,lib=None,mapping=None):
      self.name=name
      self.lib=lib
      self.mapping=mapping
   def set_name(self,name):
      self.name=name
   def set_lib(self,lib):
      self.lib=lib
   def set_map(self,mapping):
      self.mapping=mapping
   def set_all(self,name,lib,mapping):
      self.name=name
      self.lib=lib
      self.mapping=mapping
   def a(name,val):
      a_tag(name,val)
   def add(name,lib=None):
      tool_add(name,lib)
   def end():
      tool_end()
   def add_self(self):
      tool_add(self.name,self.lib)
   def start(name,lib=None):
      tool_start(name,lib)

