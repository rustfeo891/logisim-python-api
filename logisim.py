def add_comp(lib_index, x, y, name, **attrs):
   """add component with optional attributes
   eg: add_comp(LibGate[1], 200, 100, ToolNameAndGate, facing="east")
   """
   if attrs:
      comp.start(lib_index, x, y, name)
      for k, v in attrs.items():
         a.add(k, v)
      comp.end()
   else:
      comp.add(lib_index, x, y, name)

def add_pin(x, y, facing="east", output=False, label=None, width=None):
    #add an input/output pin
    attrs = {"facing": facing, "output": "true" if output else "false"}
    if label is not None:
        attrs["label"] = label
    if width is not None:
        attrs["width"] = str(width)
    add_comp(LibWiring[1], x, y, ToolNamePin, **attrs)

def add_clock(x, y, facing="east", label=None):
    #add a clock component notice that it is rising edge by default
    attrs = {"facing": facing}
    if label is not None:
        attrs["label"] = label
    add_comp(LibWiring[1], x, y, ToolNameClock, **attrs)


def add_probe(x, y, label=None, facing="east"):
    attrs = {"facing": facing}
    if label is not None:
        attrs["label"] = label
    add_comp(LibWiring[1], x, y, ToolNameProbe, **attrs)


def add_led(x, y, label=None, facing="east"):
    #add led output
    attrs = {"facing": facing}
    if label is not None:
        attrs["label"] = label
    add_comp(LibIO[1], x, y, ToolNameLED, **attrs)

def add_gate(x, y, gate_name, facing="east", label=None):
    #add a logic gate AND/OR/NOT/ORNOT
    attrs = {"facing": facing}
    if label is not None:
        attrs["label"] = label
    add_comp(LibGate[1], x, y, gate_name, **attrs)

def add_register(x, y, width=8, label=None, facing="east"):
    #add a reg with a given bit width
    attrs = {"facing": facing, "width": str(width)}
    if label is not None:
        attrs["label"] = label
    add_comp(LibMemory[1], x, y, ToolNameRegister, **attrs)

def add_splitter(x, y, fan_out, bit_width, facing="east", label=None):
    """param explain

    fan_out : eg "1,1,1,1"  or  4  (single number = N equal parts)
    bit_width : total input width
    """
    attrs = {"facing": facing,
             "fanout": str(fan_out),
             "incoming": str(bit_width)}
    if label is not None:
        attrs["label"] = label
    add_comp(LibWiring[1], x, y, ToolNameSplitter, **attrs)

def wire_bus(points):
    """
    eg:
        wire_bus([(100,100), (200,100), (200,200), (300,200)])
    """
    for (x1, y1), (x2, y2) in zip(points, points[1:]):
        wire.add(x1, y1, x2, y2)


